#!/usr/bin/env python3
"""
makecrates.py — 写出生成的 PAC crate 的公共骨架文件。

`devices/<设备>.yaml` 的每个设备对应一个 Cargo feature，以及在 `src/lib.rs`
里一行 `#[cfg(feature = "<设备>")] pub mod <设备>;`。设备模块 `src/<设备>/mod.rs`
稍后由 svd2rust 生成，所以这里写出的内容与具体设备无关，每次运行整份重写。

用法: python scripts/makecrates.py devices/ -y --families n32h7
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

SVD2RUST_VERSION = "0.37.1"

# 每个 crate 一份配置；键必须与 devices/<crate>*.yaml 的前缀一致。
CRATES: dict[str, dict] = {
    "n32h7": {
        "version": "1.0.0",
        # docs.rs 构建时 rt 是开启的，而 rt 要求恰好选中一个设备 feature，
        # 因此把设备全部列上，保证每个设备模块都能生成文档。
        "docs_devices": ["n32h760", "n32h785"],
        "doc_target": "thumbv7em-none-eabihf",
    },
}

# 除设备 feature 外，docs.rs 构建统一开启的 feature。
COMMON_DOC_FEATURES = ["atomics", "critical-section", "defmt", "rt"]


def owner_crate(device: str) -> str | None:
    """设备名归属哪个 crate：取能匹配上的最长前缀。"""
    matches = [name for name in CRATES if device.startswith(name)]
    return max(matches, key=len) if matches else None


def discover(devices_dir: Path, only: list[str]) -> dict[str, list[str]]:
    """扫描 devices_dir 下的设备 YAML，返回 crate -> 设备名列表。"""
    found: dict[str, list[str]] = {}
    for path in sorted(devices_dir.glob("*.yaml")):
        device = path.stem.lower()
        crate = owner_crate(device)
        if crate is None or (only and crate not in only):
            continue
        found.setdefault(crate, []).append(device)
    return {crate: sorted(names) for crate, names in found.items()}


def render_cargo_toml(crate: str, devices: list[str]) -> str:
    info = CRATES[crate]
    features = "\n".join(f"{device} = []" for device in devices)
    docs = ", ".join(
        f'"{feature}"' for feature in COMMON_DOC_FEATURES + info["docs_devices"]
    )
    return f"""\
[package]
edition = "2021"
name = "{crate}"
version = "{info['version']}"
description = "Device support crates for {crate.upper()} devices"
readme = "README.md"
keywords = ["{crate}", "svd2rust", "no_std", "embedded"]
categories = ["embedded", "no-std"]
license = "MIT OR Apache-2.0"
rust-version = "1.65"

[dependencies]
critical-section = {{ version = "1.0", optional = true }}
cortex-m = "0.7.7"
cortex-m-rt = {{ version = "0.7.5", optional = true }}
defmt = {{ version = "1", optional = true }}
vcell = "0.1.3"
portable-atomic = {{ version = "1", default-features = false, optional = true }}

[package.metadata.docs.rs]
features = [{docs}]
default-target = "{info['doc_target']}"
targets = []

[features]
default = ["critical-section", "rt"]
rt = ["cortex-m-rt/device"]
atomics = ["dep:portable-atomic"]
{features}
"""


def render_lib_rs(crate: str, devices: list[str]) -> str:
    family = crate.upper()
    mods = "\n".join(
        f'#[cfg(feature = "{device}")]\npub mod {device};\n' for device in devices
    )
    return f"""\
//! Peripheral access API for {family} microcontrollers
//! (generated using [svd2rust](https://github.com/rust-embedded/svd2rust)
//! {SVD2RUST_VERSION})
//!
//! You can find an overview of the API here:
//! [svd2rust/#peripheral-api](https://docs.rs/svd2rust/{SVD2RUST_VERSION}/svd2rust/#peripheral-api)
//!
//! This crate supports every {family} device; pick one with the matching
//! feature (see README). Generated from the Nationstech N32H7xx DFP SVD
//! with svdtools patches applied.

#![allow(non_camel_case_types)]
#![allow(non_snake_case)]
#![no_std]

mod generic;
pub use self::generic::*;

{mods}"""


def render_build_rs(devices: list[str]) -> str:
    names = ", ".join(f'"{device}"' for device in devices)
    return f"""\
use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {{
    if env::var_os("CARGO_FEATURE_RT").is_some() {{
        let out = PathBuf::from(env::var_os("OUT_DIR").unwrap());
        println!("cargo:rustc-link-search={{}}", out.display());
        let devices = [{names}];
        let selected = devices
            .iter()
            .find(|d| env::var_os(format!("CARGO_FEATURE_{{}}", d.to_uppercase())).is_some());
        match selected {{
            Some(device) => {{
                let device_x = format!("src/{{}}/device.x", device);
                fs::copy(&device_x, out.join("device.x")).unwrap();
                println!("cargo:rerun-if-changed={{}}", device_x);
            }}
            None => panic!(
                "no device feature selected; choose one of {{:?}}",
                devices
            ),
        }}
    }}
    println!("cargo:rerun-if-changed=build.rs");
}}
"""


def render_readme(crate: str, devices: list[str]) -> str:
    rows = "\n".join(f"* {device}" for device in devices)
    example = devices[0]
    return f"""\
# {crate}

Autogenerated peripheral access API for {crate.upper()} microcontrollers.

The code is generated by [svd2rust] from the vendor SVD with svdtools patch
files applied on top, so registers and fields carry the types and enumerated
values the chip actually has.

[svd2rust]: https://github.com/rust-embedded/svd2rust

## Usage

Every supported device sits behind its own feature gate, so only the one you
pick gets compiled:

```toml
[dependencies.{crate}]
version = "{CRATES[crate]['version']}"
features = ["{example}"]
```

The `rt` feature is on by default and pulls in `cortex-m-rt`; pass
`default-features = false` to drop it.

```rust
use {crate}::{example};

let peripherals = {example}::Peripherals::take().unwrap();
let _adc1 = &peripherals.ADC1;
```

The full API reference lives at
<https://docs.rs/svd2rust/{SVD2RUST_VERSION}/svd2rust/#peripheral-api>.

## Supported devices

{rows}
"""


def write_crate(crate: str, devices: list[str]) -> None:
    root = Path(crate)
    (root / "src").mkdir(parents=True, exist_ok=True)
    files = {
        "Cargo.toml": render_cargo_toml(crate, devices),
        "README.md": render_readme(crate, devices),
        "build.rs": render_build_rs(devices),
        "src/lib.rs": render_lib_rs(crate, devices),
    }
    for name, text in files.items():
        path = root / name
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)


def main() -> int:
    parser = argparse.ArgumentParser(description="Write the PAC crate skeleton.")
    parser.add_argument("devices", type=Path, help="存放设备 YAML 的目录")
    parser.add_argument(
        "-y", "--yes", action="store_true", help="不再询问确认"
    )
    parser.add_argument(
        "--families",
        nargs="*",
        default=[],
        metavar="FAMILY",
        help="只生成这些 crate（默认全部）",
    )
    args = parser.parse_args()

    plan = discover(args.devices, args.families)
    if not plan:
        print(f"no device YAML found in {args.devices}", file=sys.stderr)
        return 1

    print("Going to create/update: " + ", ".join(f"{crate}/" for crate in plan))
    if not args.yes:
        input("press Enter to continue, Ctrl-C to cancel")

    for crate, devices in plan.items():
        write_crate(crate, devices)
        print(f"crate {crate}: {len(devices)} device(s): {', '.join(devices)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
